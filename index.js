async function sendLongMessage(chatId, text) {
  const maxLength = 4000;
  const message = String(text || "").trim();

  if (!message) {
    await bot.sendMessage(chatId, "Не вдалося сформувати відповідь. Спробуй, будь ласка, ще раз.");
    return;
  }

  for (let i = 0; i < message.length; i += maxLength) {
    await bot.sendMessage(chatId, message.slice(i, i + maxLength));
  }
}

bot.on("message", async (msg) => {
  const chatId = msg.chat?.id;
  const userText = msg.text?.trim();

  if (!chatId || !userText) return;

  try {
    await bot.sendChatAction(chatId, "typing");

    const completion = await openai.chat.completions.create({
      model: "gpt-4o-mini",
      max_completion_tokens: 1000,
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user", content: userText },
      ],
    });

    const gptReply = completion.choices?.[0]?.message?.content?.trim();

    await sendLongMessage(
      chatId,
      gptReply || "Не вдалося сформувати відповідь. Спробуй, будь ласка, ще раз."
    );
  } catch (err) {
    console.error("Помилка під час обробки повідомлення:", {
      message: err?.message,
      status: err?.status,
      code: err?.code,
    });

    try {
      await bot.sendMessage(
        chatId,
        "Вибач, зараз сервіс тимчасово недоступний. Спробуй пізніше 🙏"
      );
    } catch (telegramErr) {
      console.error("Не вдалося надіслати повідомлення в Telegram:", telegramErr?.message);
    }
  }
});

bot.on("polling_error", (err) => {
  console.error("Помилка Telegram polling:", err?.message || err);
});

console.log("ModernEcoBot запущений і готовий до роботи.");
